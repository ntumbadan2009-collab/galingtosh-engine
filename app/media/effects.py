from __future__ import annotations
import math
from pathlib import Path
from typing import Any
from app.media.ffmpeg import run_ffmpeg

_ALLOWED={"fade_in","fade_out","grayscale","vignette","text_overlay"}

# User text is data, never part of the FFmpeg filter grammar.
# The renderer supplies its private work directory for overlay text files.

def _filter_path(path: Path) -> str:
    return str(path.resolve()).replace("\\", "/").replace(":", "\\:")

def build_video_filters(effects:list[dict[str,Any]],duration:float,width:int,height:int, targets:dict[str,tuple[float,float]]|None=None, *, text_directory:Path|None=None)->tuple[list[str],list[str]]:
    filters=[]; warnings=[]
    for effect in effects:
        if not isinstance(effect,dict): continue
        kind=str(effect.get("type",""))
        if kind=="title_overlay": kind="text_overlay"
        if kind not in _ALLOWED:
            warnings.append(f"Effet « {kind} » non pris en charge : ignoré."); continue
        target = effect.get("target", "film")
        if target != "film" and (not targets or target not in targets):
            warnings.append(f"Cible d’effet inconnue : {target}. Effet ignoré."); continue
        begin, end = (targets or {}).get(target, (0.0, duration))
        before = len(filters)
        params=effect.get("params") or {}
        if not isinstance(params,dict):
            warnings.append(f"Paramètres invalides pour l’effet « {kind} » : ignoré."); continue
        try:
            if kind=="grayscale": filters.append("hue=s=0")
            elif kind=="vignette": filters.append("vignette=PI/5")
            elif kind in {"fade_in","fade_out"}:
                seconds=float(params.get("durationSec",1))
                if not math.isfinite(seconds): raise ValueError
                seconds=max(0.05,min(5.0,seconds,end-begin))
                if kind=="fade_in": filters.append(f"fade=t=in:st={begin:.3f}:d={seconds:.3f}")
                else: filters.append(f"fade=t=out:st={max(begin,end-seconds):.3f}:d={seconds:.3f}")
            elif kind=="text_overlay":
                text=str(params.get("text",""))[:300].replace("\x00","").replace("\n"," ")
                if text:
                    size=int(params.get("fontSize",max(24,width//28)))
                    size=max(12,min(96,size))
                    position=str(params.get("position","bottom")).lower()
                    y="2*text_h" if position=="top" else "h-3*text_h" if position=="bottom" else "(h-text_h)/2"
                    if text_directory is None:
                        raise ValueError("text_directory required for text overlays")
                    title_file = text_directory / f"overlay_{len(filters):04d}.txt"
                    title_file.write_text(text, encoding="utf-8")
                    # The path is generated by the renderer, not supplied by the user.
                    filters.append(f"drawtext=textfile='{_filter_path(title_file)}':expansion=none:fontcolor=white:fontsize={size}:borderw=2:bordercolor=black:x=(w-text_w)/2:y={y}")
            if len(filters)>before and target!="film":
                filters[-1] += f":enable='between(t,{begin:.4f},{end:.4f})'"
        except (TypeError,ValueError,OverflowError):
            warnings.append(f"Paramètres invalides pour l’effet « {kind} » : ignoré.")
    return filters,warnings

async def finish_video(source:Path,destination:Path,filters:list[str],subtitle_file:Path|None=None)->None:
    applied=list(filters)
    if subtitle_file and subtitle_file.is_file():
        path=str(subtitle_file.resolve()).replace("\\","/").replace(":","\\:")
        applied.append(f"subtitles='{path}':force_style='FontName=DejaVu Sans,FontSize=24,Outline=2,Shadow=1,MarginV=36'")
    if not applied:
        source.replace(destination); return
    await run_ffmpeg(["-i",str(source),"-vf",",".join(applied),"-map","0:v:0","-map","0:a?",
        "-c:v","libx264","-preset","ultrafast","-b:v","2300k","-maxrate","2800k","-bufsize","4600k","-threads","1","-pix_fmt","yuv420p",
        "-c:a","aac","-b:a","128k","-movflags","+faststart",str(destination)])

